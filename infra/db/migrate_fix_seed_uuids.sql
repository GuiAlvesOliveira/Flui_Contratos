-- migrate_fix_seed_uuids.sql
-- Replaces non-RFC-4122 seed IDs with proper v4 UUIDs.
-- The original seed used IDs like 00000000-0000-0000-0003-000000000001 whose
-- 4th segment (0003) doesn't start with 8/9/a/b — those fail @IsUUID() validation.
--
-- Run once against the dev/test database:
--   psql <connection-string> -f infra/db/migrate_fix_seed_uuids.sql
--
-- New ID mapping:
--   tenant   00000000-0000-0000-0000-000000000001 → a0000000-0000-4000-8000-000000000001
--   user(1)  00000000-0000-0000-0001-000000000001 → b0000000-0000-4000-8000-000000000001
--   user(2)  00000000-0000-0000-0001-000000000002 → b0000000-0000-4000-8000-000000000002
--   user(3)  00000000-0000-0000-0001-000000000003 → b0000000-0000-4000-8000-000000000003
--   user(4)  00000000-0000-0000-0001-000000000004 → b0000000-0000-4000-8000-000000000004
--   emp(1)   00000000-0000-0000-0003-000000000001 → c0000000-0000-4000-8000-000000000001
--   emp(2)   00000000-0000-0000-0003-000000000002 → c0000000-0000-4000-8000-000000000002
--   unidade(1) 00000000-0000-0000-0004-000000000001 → d0000000-0000-4000-8000-000000000001
--   unidade(2) 00000000-0000-0000-0004-000000000002 → d0000000-0000-4000-8000-000000000002
--   process(1) 00000000-0000-0000-0002-000000000001 → e0000000-0000-4000-8000-000000000001

BEGIN;

-- Disable FK checks for the duration of this transaction
SET session_replication_role = 'replica';

-- ── 1. Tenants ──────────────────────────────────────────────────────────────────
UPDATE tenants
   SET id = 'a0000000-0000-4000-8000-000000000001'
 WHERE id = '00000000-0000-0000-0000-000000000001';

-- ── 2. Users ────────────────────────────────────────────────────────────────────
-- FK: tenant_id
UPDATE users SET tenant_id = 'a0000000-0000-4000-8000-000000000001'
 WHERE tenant_id = '00000000-0000-0000-0000-000000000001';

-- FK: created_by (self-ref)
UPDATE users SET created_by = 'b0000000-0000-4000-8000-000000000002'
 WHERE created_by = '00000000-0000-0000-0001-000000000002';
UPDATE users SET created_by = 'b0000000-0000-4000-8000-000000000003'
 WHERE created_by = '00000000-0000-0000-0001-000000000003';
UPDATE users SET created_by = 'b0000000-0000-4000-8000-000000000004'
 WHERE created_by = '00000000-0000-0000-0001-000000000004';

-- Primary keys
UPDATE users SET id = 'b0000000-0000-4000-8000-000000000001' WHERE id = '00000000-0000-0000-0001-000000000001';
UPDATE users SET id = 'b0000000-0000-4000-8000-000000000002' WHERE id = '00000000-0000-0000-0001-000000000002';
UPDATE users SET id = 'b0000000-0000-4000-8000-000000000003' WHERE id = '00000000-0000-0000-0001-000000000003';
UPDATE users SET id = 'b0000000-0000-4000-8000-000000000004' WHERE id = '00000000-0000-0000-0001-000000000004';

-- ── 3. Empreendimentos ──────────────────────────────────────────────────────────
UPDATE empreendimentos SET tenant_id = 'a0000000-0000-4000-8000-000000000001'
 WHERE tenant_id = '00000000-0000-0000-0000-000000000001';

UPDATE empreendimentos SET id = 'c0000000-0000-4000-8000-000000000001' WHERE id = '00000000-0000-0000-0003-000000000001';
UPDATE empreendimentos SET id = 'c0000000-0000-4000-8000-000000000002' WHERE id = '00000000-0000-0000-0003-000000000002';

-- ── 4. Unidades ─────────────────────────────────────────────────────────────────
UPDATE unidades SET tenant_id = 'a0000000-0000-4000-8000-000000000001'
 WHERE tenant_id = '00000000-0000-0000-0000-000000000001';

UPDATE unidades SET empreendimento_id = 'c0000000-0000-4000-8000-000000000001'
 WHERE empreendimento_id = '00000000-0000-0000-0003-000000000001';
UPDATE unidades SET empreendimento_id = 'c0000000-0000-4000-8000-000000000002'
 WHERE empreendimento_id = '00000000-0000-0000-0003-000000000002';

UPDATE unidades SET id = 'd0000000-0000-4000-8000-000000000001' WHERE id = '00000000-0000-0000-0004-000000000001';
UPDATE unidades SET id = 'd0000000-0000-4000-8000-000000000002' WHERE id = '00000000-0000-0000-0004-000000000002';

-- ── 5. Processes ────────────────────────────────────────────────────────────────
UPDATE processes SET tenant_id = 'a0000000-0000-4000-8000-000000000001'
 WHERE tenant_id = '00000000-0000-0000-0000-000000000001';

UPDATE processes SET client_id  = 'b0000000-0000-4000-8000-000000000001' WHERE client_id  = '00000000-0000-0000-0001-000000000001';
UPDATE processes SET client_id  = 'b0000000-0000-4000-8000-000000000002' WHERE client_id  = '00000000-0000-0000-0001-000000000002';
UPDATE processes SET client_id  = 'b0000000-0000-4000-8000-000000000003' WHERE client_id  = '00000000-0000-0000-0001-000000000003';
UPDATE processes SET client_id  = 'b0000000-0000-4000-8000-000000000004' WHERE client_id  = '00000000-0000-0000-0001-000000000004';

UPDATE processes SET analista_id = 'b0000000-0000-4000-8000-000000000001' WHERE analista_id = '00000000-0000-0000-0001-000000000001';
UPDATE processes SET analista_id = 'b0000000-0000-4000-8000-000000000002' WHERE analista_id = '00000000-0000-0000-0001-000000000002';
UPDATE processes SET analista_id = 'b0000000-0000-4000-8000-000000000003' WHERE analista_id = '00000000-0000-0000-0001-000000000003';
UPDATE processes SET analista_id = 'b0000000-0000-4000-8000-000000000004' WHERE analista_id = '00000000-0000-0000-0001-000000000004';

UPDATE processes SET unidade_id = 'd0000000-0000-4000-8000-000000000001' WHERE unidade_id = '00000000-0000-0000-0004-000000000001';
UPDATE processes SET unidade_id = 'd0000000-0000-4000-8000-000000000002' WHERE unidade_id = '00000000-0000-0000-0004-000000000002';

UPDATE processes SET id = 'e0000000-0000-4000-8000-000000000001' WHERE id = '00000000-0000-0000-0002-000000000001';

-- ── 6. Documents ────────────────────────────────────────────────────────────────
UPDATE documents SET tenant_id = 'a0000000-0000-4000-8000-000000000001'
 WHERE tenant_id = '00000000-0000-0000-0000-000000000001';

UPDATE documents SET process_id = 'e0000000-0000-4000-8000-000000000001'
 WHERE process_id = '00000000-0000-0000-0002-000000000001';

UPDATE documents SET user_id       = 'b0000000-0000-4000-8000-000000000004' WHERE user_id       = '00000000-0000-0000-0001-000000000004';
UPDATE documents SET validated_by  = 'b0000000-0000-4000-8000-000000000002' WHERE validated_by  = '00000000-0000-0000-0001-000000000002';
UPDATE documents SET validated_by  = 'b0000000-0000-4000-8000-000000000003' WHERE validated_by  = '00000000-0000-0000-0001-000000000003';
UPDATE documents SET uploaded_by   = 'b0000000-0000-4000-8000-000000000002' WHERE uploaded_by   = '00000000-0000-0000-0001-000000000002';
UPDATE documents SET uploaded_by   = 'b0000000-0000-4000-8000-000000000003' WHERE uploaded_by   = '00000000-0000-0000-0001-000000000003';
UPDATE documents SET uploaded_by   = 'b0000000-0000-4000-8000-000000000004' WHERE uploaded_by   = '00000000-0000-0000-0001-000000000004';

-- ── 7. Process participants ──────────────────────────────────────────────────────
UPDATE process_participants SET tenant_id  = 'a0000000-0000-4000-8000-000000000001'
 WHERE tenant_id = '00000000-0000-0000-0000-000000000001';

UPDATE process_participants SET process_id = 'e0000000-0000-4000-8000-000000000001'
 WHERE process_id = '00000000-0000-0000-0002-000000000001';

-- ── 8. Audit logs ────────────────────────────────────────────────────────────────
UPDATE audit_logs SET tenant_id  = 'a0000000-0000-4000-8000-000000000001'
 WHERE tenant_id = '00000000-0000-0000-0000-000000000001';

UPDATE audit_logs SET process_id = 'e0000000-0000-4000-8000-000000000001'
 WHERE process_id = '00000000-0000-0000-0002-000000000001';

UPDATE audit_logs SET actor_id = 'b0000000-0000-4000-8000-000000000001' WHERE actor_id = '00000000-0000-0000-0001-000000000001';
UPDATE audit_logs SET actor_id = 'b0000000-0000-4000-8000-000000000002' WHERE actor_id = '00000000-0000-0000-0001-000000000002';
UPDATE audit_logs SET actor_id = 'b0000000-0000-4000-8000-000000000003' WHERE actor_id = '00000000-0000-0000-0001-000000000003';
UPDATE audit_logs SET actor_id = 'b0000000-0000-4000-8000-000000000004' WHERE actor_id = '00000000-0000-0000-0001-000000000004';

-- Re-enable FK checks
SET session_replication_role = 'origin';

COMMIT;
